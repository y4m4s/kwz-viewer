import { test, expect } from '@playwright/test';
import { existsSync } from 'node:fs';
import { mkdir } from 'node:fs/promises';
import path from 'node:path';

test('real KWZ: gallery, thumbnail, animation, audio, seek and close', async ({ page, request }) => {
  test.skip(!existsSync(process.env.KWZ_TEST_DIRECTORY || path.resolve('data')), '実KWZフォルダが必要です');
  const errors: string[] = []; const external: string[] = [];
  page.on('pageerror', e => errors.push(e.message));
  page.on('request', r => { if (!r.url().startsWith('http://127.0.0.1:4183/')) external.push(r.url()); });
  await page.addInitScript(() => {
    const audit = { started: 0, stopped: 0, closed: 0, nonSilent: false, running: false };
    Object.assign(window, { audioAudit: audit });
    const close = AudioContext.prototype.close;
    AudioContext.prototype.close = function () { audit.closed++; return close.call(this); };
    const original = AudioContext.prototype.createBufferSource;
    AudioContext.prototype.createBufferSource = function () {
      const source = original.call(this); const context = this;
      const start = source.start.bind(source); const stop = source.stop.bind(source);
      source.start = (...args: Parameters<typeof start>) => {
        audit.started++; audit.running = context.state === 'running';
        if (source.buffer) audit.nonSilent ||= source.buffer.getChannelData(0).some(v => v !== 0);
        return start(...args);
      };
      source.stop = (...args: Parameters<typeof stop>) => { audit.stopped++; return stop(...args); };
      return source;
    };
  });
  await expect.poll(async () => (await request.get('/api/health')).json().then(s => s.scanStatus)).toBe('ready');
  await page.goto('/');
  await expect(page.getByRole('button', { name: 'みる', exact: true })).toBeVisible();
  await page.getByRole('button', { name: 'みる', exact: true }).click();
  const first = page.locator('.note-card').first(); await expect(first).toBeVisible();
  await expect(first.locator('img')).toBeVisible();
  await expect.poll(() => first.locator('img').evaluate((img: HTMLImageElement) => img.naturalWidth)).toBe(320);
  await mkdir('.app-data/validation', { recursive: true });
  await page.screenshot({ path: '.app-data/validation/gallery.png', fullPage: false });
  await first.click(); const modal = page.getByRole('dialog'); await expect(modal).toBeVisible();
  await expect(modal.getByRole('button', { name: '再生', exact: true })).toBeEnabled();
  const seek = modal.getByRole('slider', { name: 'シーク' });
  const totalPages = Number(await seek.getAttribute('max'));
  await expect(seek).toHaveAttribute('min', '0');
  await expect(seek).toHaveAttribute('step', '1');
  await expect(modal.locator('.playback > span')).toHaveText(`0 / ${totalPages}`);
  await expect(seek).toHaveValue('0');
  for (const viewport of [{ width: 1280, height: 720 }, { width: 1024, height: 600 }, { width: 900, height: 480 }, { width: 390, height: 844 }]) {
    await page.setViewportSize(viewport);
    await expect(modal.locator('.player-stage')).toBeInViewport({ ratio: 1 });
    await expect(seek).toBeInViewport({ ratio: 1 });
    await expect(modal.getByRole('slider', { name: '音量' })).toBeInViewport({ ratio: 1 });
    await expect(modal.getByRole('button', { name: 'ループ', exact: true })).toBeInViewport({ ratio: 1 });
    expect(await modal.evaluate(element => element.scrollWidth <= element.clientWidth)).toBe(true);
  }
  await page.setViewportSize({ width: 1280, height: 900 });
  await expect(modal.getByText('作者', { exact: true })).toBeVisible();
  const controlsBox = await modal.locator('.audio-controls').boundingBox();
  const detailsBox = await modal.locator('.details').boundingBox();
  expect(detailsBox!.y).toBeGreaterThan(controlsBox!.y + controlsBox!.height);
  const overlay = modal.locator('.stage-play');
  const overlayIcon = overlay.locator('.stage-play-icon');
  await modal.getByRole('button', { name: '閉じる' }).hover();
  await expect(overlayIcon).toHaveCSS('opacity', '0');
  await modal.locator('.player-stage').hover();
  await expect(overlayIcon).toHaveCSS('opacity', '0.5');
  await expect(overlayIcon).toHaveCSS('width', '88px');
  await expect(overlayIcon).toHaveCSS('height', '88px');
  const stageBox = await modal.locator('.player-stage').boundingBox();
  const buttonBox = await overlayIcon.boundingBox();
  const hitBox = await overlay.boundingBox();
  expect(hitBox!.width).toBeCloseTo(stageBox!.width);
  expect(hitBox!.height).toBeCloseTo(stageBox!.height);
  expect(Math.abs(buttonBox!.x + buttonBox!.width / 2 - (stageBox!.x + stageBox!.width / 2))).toBeLessThan(1);
  expect(Math.abs(buttonBox!.y + buttonBox!.height / 2 - (stageBox!.y + stageBox!.height / 2))).toBeLessThan(1);
  await modal.getByRole('button', { name: '映像上で再生', exact: true }).click({ position: { x: 8, y: 8 } });
  await expect(modal.getByRole('button', { name: '一時停止', exact: true })).toBeVisible();
  await expect(seek).toHaveAttribute('min', '1');
  await expect.poll(async () => Number(await seek.inputValue())).toBeGreaterThanOrEqual(1);
  await expect(overlay.locator('rect')).toBeVisible();
  await modal.getByRole('button', { name: '映像上で停止', exact: true }).click({ position: { x: hitBox!.width - 8, y: hitBox!.height - 8 } });
  await expect(modal.getByRole('button', { name: '再生', exact: true })).toBeEnabled();
  await expect(overlay.locator('path')).toBeVisible();
  await page.screenshot({ path: '.app-data/validation/player-hover.png' });
  await modal.getByRole('button', { name: '閉じる' }).hover();
  await modal.getByRole('button', { name: '再生', exact: true }).focus();
  await page.keyboard.press('Shift+Tab');
  await expect(overlay).toBeFocused();
  await expect(overlayIcon).toHaveCSS('opacity', '0.5');
  await modal.getByRole('button', { name: '再生', exact: true }).click();
  await expect(modal.getByRole('button', { name: '一時停止' })).toBeVisible();
  await expect.poll(async () => Number(await modal.getByRole('slider', { name: 'シーク' }).inputValue())).toBeGreaterThan(1);
  await expect.poll(() => page.evaluate(() => (window as unknown as { audioAudit: { nonSilent: boolean } }).audioAudit.nonSilent)).toBe(true);
  const audio = await page.evaluate(() => (window as unknown as { audioAudit: unknown }).audioAudit);
  console.log('Browser real KWZ audio:', JSON.stringify(audio));
  await page.screenshot({ path: '.app-data/validation/player.png' });
  await modal.getByRole('button', { name: '一時停止' }).click();
  const position = await modal.getByRole('slider', { name: 'シーク' }).inputValue();
  await page.waitForTimeout(250); expect(await modal.getByRole('slider', { name: 'シーク' }).inputValue()).toBe(position);
  const beforeSeek = await modal.locator('canvas').screenshot();
  const middlePage = Math.max(1, Math.floor(totalPages / 2));
  await seek.fill(String(middlePage));
  await expect(modal.locator('.playback > span')).toHaveText(`${middlePage} / ${totalPages}`);
  const afterSeek = await modal.locator('canvas').screenshot();
  expect(beforeSeek.equals(afterSeek)).toBe(false);
  await seek.fill(String(totalPages));
  await expect(modal.locator('.playback > span')).toHaveText(`${totalPages} / ${totalPages}`);
  await seek.fill('1');
  await expect(modal.locator('.playback > span')).toHaveText(`1 / ${totalPages}`);
  await modal.getByRole('slider', { name: '音量' }).fill('0.5');
  const loopButton = modal.getByRole('button', { name: 'ループ', exact: true });
  if (await loopButton.getAttribute('aria-pressed') === 'true') await loopButton.click();
  await expect(loopButton).toHaveAttribute('aria-pressed', 'false');
  await loopButton.click();
  await expect(loopButton).toHaveAttribute('aria-pressed', 'true');
  await loopButton.click();
  await expect(loopButton).toHaveAttribute('aria-pressed', 'false');
  await loopButton.click();
  await modal.getByRole('button', { name: '再生', exact: true }).click();
  await modal.getByRole('button', { name: '閉じる' }).click(); await expect(modal).not.toBeVisible();
  await expect.poll(() => page.evaluate(() => (window as unknown as { audioAudit: { closed: number } }).audioAudit.closed)).toBeGreaterThan(0);
  await expect(first).toBeVisible();
  expect(errors).toEqual([]); expect(external).toEqual([]);
});
